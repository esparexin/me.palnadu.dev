import {readdirSync, readFileSync} from 'node:fs';
import {join} from 'node:path';
import {describe, expect, it} from 'vitest';

/**
 * Lint coverage check.
 *
 * Each workspace lints a fixed list of directories. When `apps/api` gained a `test/`
 * directory in Phase 6B, its lint script still read `eslint src`, so nothing under
 * `apps/api/test` was linted by any script - local or CI. That is how an unused import
 * survived into `main` and was found only by CodeQL.
 *
 * The failure is silent by construction: an unlinted directory produces no errors, so
 * every lint job stays green while the coverage disappears. This test makes the
 * omission loud instead.
 */

const ROOT = new URL('../..', import.meta.url).pathname;
const SKIP_DIRECTORIES = new Set([
  'node_modules',
  'dist',
  '.next',
  '.turbo',
  'coverage',
  '.git',
  '.me-palnadu-test-replica',
]);

const workspaceScripts = () => {
  const roots = ['apps', 'packages'];
  const found = [];
  for (const group of roots) {
    for (const name of readdirSync(join(ROOT, group))) {
      // Read the manifest once and treat any failure as "not a workspace". A
      // `statSync` followed by a `readFileSync` is a check-then-use pair: CodeQL
      // reports it as js/file-system-race, and it is genuinely racy even here, where
      // the window is a test run rather than a request.
      let manifest;
      try {
        manifest = JSON.parse(readFileSync(join(ROOT, group, name, 'package.json'), 'utf8'));
      } catch {
        continue;
      }
      found.push({name: `${group}/${name}`, lint: manifest.scripts?.lint ?? ''});
    }
  }
  return found;
};

const typescriptFiles = (relativeRoot) => {
  const results = [];
  const walk = (absolute, relativePath) => {
    for (const entry of readdirSync(absolute, {withFileTypes: true})) {
      if (entry.name.startsWith('.') || SKIP_DIRECTORIES.has(entry.name)) continue;
      const child = join(absolute, entry.name);
      const childRelative = join(relativePath, entry.name);
      if (entry.isDirectory()) walk(child, childRelative);
      // `next-env.d.ts` is generated by Next.js on every run; linting it would only
      // report on a file the author does not control.
      else if (/\.(ts|tsx|mts|cts)$/.test(entry.name) && entry.name !== 'next-env.d.ts') {
        results.push(childRelative);
      }
    }
  };
  const absolute = join(ROOT, relativeRoot);
  try {
    readdirSync(absolute);
  } catch {
    // No such directory: nothing to cover, and walking it would throw.
    return results;
  }
  walk(absolute, relativeRoot);
  return results;
};

/**
 * A file is covered when one of the entries in the lint script matches it.
 *
 * ESLint recurses, so `eslint src` already covers `src/auth/controller.ts`. Entries may
 * be a directory, an ancestor of one, or a shell glob such as `*.ts` for the files
 * sitting directly in the workspace root. Treating the deepest directory as the unit,
 * as a first attempt did, reported every nested file as uncovered and made the check
 * useless rather than strict.
 */
const matchesGlob = (pattern, candidate) => {
  const expression = pattern
    .split('')
    .map((character) => {
      if (character === '*') return '[^/]*';
      return character.replace(/[.+^${}()|[\]\\]/g, '\\$&');
    })
    .join('');
  return new RegExp(`^${expression}$`).test(candidate);
};

const isCovered = (workspaceRoot, file, lintPaths) => {
  const withinWorkspace = file.slice(workspaceRoot.length + 1);
  return lintPaths.some((lintPath) => {
    const normalised = lintPath.replace(/^\.\//, '').replace(/\/$/, '');
    if (normalised.includes('*')) {
      // A glob is matched against the file path within the workspace.
      return matchesGlob(normalised, withinWorkspace);
    }
    return withinWorkspace === normalised || withinWorkspace.startsWith(`${normalised}/`);
  });
};

describe('lint coverage', () => {
  it('has a lint script for every workspace', () => {
    const missing = workspaceScripts().filter((workspace) => workspace.lint.length === 0);
    expect(missing.map((workspace) => workspace.name)).toEqual([]);
  });

  it('lints every TypeScript file in every workspace', () => {
    const uncovered = [];
    for (const workspace of workspaceScripts()) {
      const lintPaths = workspace.lint
        .split(/\s+/)
        .filter((token) => !token.startsWith('-') && !token.includes('eslint'));
      for (const file of typescriptFiles(workspace.name)) {
        if (!isCovered(workspace.name, file, lintPaths)) uncovered.push(file);
      }
    }
    expect(uncovered).toEqual([]);
  });

  it('still lints the repository scripts and root tests', () => {
    const manifest = JSON.parse(readFileSync(join(ROOT, 'package.json'), 'utf8'));
    expect(manifest.scripts['lint:repo']).toContain('scripts');
    expect(manifest.scripts['lint:repo']).toContain('tests');
  });
});
