/**
 * Markdown subset renderer (ADR-0010 §2).
 *
 * The Knowledge Hub stores Markdown source. This module parses the subset the
 * repository needs into a small, typed AST. It never produces HTML strings, so
 * there is no `dangerouslySetInnerHTML` in the path and raw HTML in an article is
 * rendered as text rather than interpreted.
 *
 * Supported: `##`–`####` headings, paragraphs, unordered and ordered lists,
 * fenced code blocks, blockquotes, horizontal rules, and inline code, bold,
 * italic, and links.
 *
 * Deliberately unsupported: raw HTML, tables, footnotes, images, and nested
 * lists. Adding one is a change to this parser plus a test, not a configuration
 * flag on a dependency.
 */

export type InlineNode =
  | {type: 'text'; value: string}
  | {type: 'code'; value: string}
  | {type: 'strong'; children: InlineNode[]}
  | {type: 'emphasis'; children: InlineNode[]}
  | {type: 'link'; href: string; children: InlineNode[]};

export type BlockNode =
  | {type: 'heading'; depth: 2 | 3 | 4; id: string; children: InlineNode[]}
  | {type: 'paragraph'; children: InlineNode[]}
  | {type: 'code'; language: string; value: string}
  | {type: 'quote'; children: InlineNode[]}
  | {type: 'list'; ordered: boolean; items: InlineNode[][]}
  | {type: 'rule'};

export interface Heading {
  depth: 2 | 3 | 4;
  id: string;
  text: string;
}

const SLUG_SEPARATOR = /[^a-z0-9]+/gu;

/**
 * Heading id, matching the slug rule so a table of contents link and the heading
 * anchor are generated by the same function.
 */
export const headingId = (text: string): string =>
  text
    .normalize('NFKD')
    .replace(/[\u0300-\u036f]/gu, '')
    .toLowerCase()
    .replace(SLUG_SEPARATOR, '-')
    .replace(/^-+|-+$/gu, '');

/** Splits text on a delimiter while keeping the delimiters out of the result. */
const parseInline = (source: string): InlineNode[] => {
  const nodes: InlineNode[] = [];
  let rest = source;

  const patterns: ReadonlyArray<{
    regex: RegExp;
    build: (match: RegExpExecArray) => InlineNode;
  }> = [
    {
      regex: /`([^`]+)`/u,
      build: (match) => ({type: 'code', value: match[1] ?? ''}),
    },
    {
      regex: /\*\*([^*]+)\*\*/u,
      build: (match) => ({type: 'strong', children: parseInline(match[1] ?? '')}),
    },
    {
      regex: /(?<!\*)\*([^*]+)\*(?!\*)/u,
      build: (match) => ({type: 'emphasis', children: parseInline(match[1] ?? '')}),
    },
    {
      regex: /\[([^\]]+)\]\(([^)\s]+)\)/u,
      build: (match) => ({
        type: 'link',
        href: safeHref(match[2] ?? ''),
        children: parseInline(match[1] ?? ''),
      }),
    },
  ];

  while (rest.length > 0) {
    let earliest: {
      index: number;
      match: RegExpExecArray;
      build: (m: RegExpExecArray) => InlineNode;
    } | null = null;

    for (const pattern of patterns) {
      const match = pattern.regex.exec(rest);
      if (match === null) continue;
      if (earliest === null || match.index < earliest.index) {
        earliest = {index: match.index, match, build: pattern.build};
      }
    }

    if (earliest === null) {
      nodes.push({type: 'text', value: rest});
      break;
    }

    if (earliest.index > 0) {
      nodes.push({type: 'text', value: rest.slice(0, earliest.index)});
    }
    nodes.push(earliest.build(earliest.match));
    rest = rest.slice(earliest.index + earliest.match[0].length);
  }

  return nodes.filter((node) => node.type !== 'text' || node.value.length > 0);
};

/**
 * Only http(s) and site-relative links survive.
 *
 * A `javascript:` link in stored Markdown would be rendered as an anchor by React;
 * React does not block the scheme, so it is refused here rather than trusted.
 */
const safeHref = (href: string): string => {
  if (href.startsWith('/') && !href.startsWith('//')) return href;
  if (/^https?:\/\//iu.test(href)) return href;
  return '#';
};

/** Plain text of an inline tree, for heading ids and accessible labels. */
const inlineText = (nodes: InlineNode[]): string =>
  nodes
    .map((node) => {
      if (node.type === 'text' || node.type === 'code') return node.value;
      if (node.type === 'link') return inlineText(node.children);
      return inlineText(node.children);
    })
    .join('');

const HEADING = /^(#{2,4})\s+(.+)$/u;
const FENCE = /^```([A-Za-z0-9_+-]*)\s*$/u;
const UNORDERED = /^[-*]\s+(.+)$/u;
const ORDERED = /^\d+\.\s+(.+)$/u;
const RULE = /^(-{3,}|\*{3,}|_{3,})$/u;
const QUOTE = /^>\s?(.*)$/u;

/** Parses Markdown source into blocks. */
export const parseMarkdown = (source: string): BlockNode[] => {
  const blocks: BlockNode[] = [];
  const lines = source.replace(/\r\n/gu, '\n').split('\n');
  let index = 0;

  while (index < lines.length) {
    const line = lines[index] ?? '';
    if (line.trim().length === 0) {
      index += 1;
      continue;
    }

    const fence = FENCE.exec(line.trim());
    if (fence !== null) {
      const language = fence[1] ?? '';
      const body: string[] = [];
      index += 1;
      while (index < lines.length && !(lines[index] ?? '').trim().startsWith('```')) {
        body.push(lines[index] ?? '');
        index += 1;
      }
      index += 1;
      blocks.push({type: 'code', language, value: body.join('\n')});
      continue;
    }

    const heading = HEADING.exec(line);
    if (heading !== null) {
      const depth = heading[1]?.length as 2 | 3 | 4;
      const children = parseInline((heading[2] ?? '').trim());
      blocks.push({type: 'heading', depth, id: headingId(inlineText(children)), children});
      index += 1;
      continue;
    }

    if (RULE.test(line.trim())) {
      blocks.push({type: 'rule'});
      index += 1;
      continue;
    }

    if (QUOTE.test(line)) {
      const body: string[] = [];
      while (index < lines.length && QUOTE.test(lines[index] ?? '')) {
        body.push(QUOTE.exec(lines[index] ?? '')?.[1] ?? '');
        index += 1;
      }
      blocks.push({type: 'quote', children: parseInline(body.join(' '))});
      continue;
    }

    if (UNORDERED.test(line) || ORDERED.test(line)) {
      const ordered = ORDERED.test(line);
      const matcher = ordered ? ORDERED : UNORDERED;
      const items: InlineNode[][] = [];
      while (index < lines.length) {
        const current = lines[index] ?? '';
        const match = matcher.exec(current);
        if (match === null) break;
        items.push(parseInline(match[1] ?? ''));
        index += 1;
      }
      blocks.push({type: 'list', ordered, items});
      continue;
    }

    const paragraph: string[] = [];
    while (index < lines.length) {
      const current = lines[index] ?? '';
      if (
        current.trim().length === 0 ||
        HEADING.test(current) ||
        FENCE.test(current.trim()) ||
        RULE.test(current.trim()) ||
        QUOTE.test(current) ||
        UNORDERED.test(current) ||
        ORDERED.test(current)
      ) {
        break;
      }
      paragraph.push(current.trim());
      index += 1;
    }
    blocks.push({type: 'paragraph', children: parseInline(paragraph.join(' '))});
  }

  return blocks;
};

/** Every heading in document order, for a table of contents. */
export const extractHeadings = (blocks: readonly BlockNode[]): Heading[] =>
  blocks.flatMap((block) =>
    block.type === 'heading'
      ? [{depth: block.depth, id: block.id, text: inlineText(block.children)}]
      : [],
  );

/** Plain text of the whole document, used for reading time and excerpts. */
export const markdownToPlainText = (source: string): string =>
  parseMarkdown(source)
    .map((block) => {
      switch (block.type) {
        case 'heading':
        case 'paragraph':
        case 'quote':
          return inlineText(block.children);
        case 'list':
          return block.items.map(inlineText).join(' ');
        case 'code':
          return block.value;
        case 'rule':
          return '';
        default:
          return '';
      }
    })
    .filter((part) => part.length > 0)
    .join('\n\n');

export const inlineToText = inlineText;
